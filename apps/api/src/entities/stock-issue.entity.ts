import {
  Column,
  CreateDateColumn,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  OneToMany,
  PrimaryGeneratedColumn,
  UpdateDateColumn,
} from 'typeorm';
import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { User } from './user.entity';
import { StockCustody } from './stock-custody.entity';
import { StockIssueItem } from './stock-issue-item.entity';

export enum StockIssueStatus {
  /** Owner has offered the volume; awaiting the custodian's acceptance. */
  PENDING = 'PENDING',
  /** Custodian accepted — lots split, `custodian_id` stamped. */
  ACCEPTED = 'ACCEPTED',
  /** Custodian refused the volume. No side effects. */
  REJECTED = 'REJECTED',
  /** Owner withdrew the offer. Only allowed while PENDING. */
  CANCELLED = 'CANCELLED',
}

/**
 * Handing a volume of branch stock to a custodian (`SHOP_CUSTODY_PLAN.md` §3.2).
 *
 * Two-step on purpose: the custodian **accepts** what they are given, which is
 * what makes the later handover a fair check — the quantities were agreed by
 * both parties, not asserted by one. Modelled on {@link ConsignmentRequest},
 * but internal to the business, so it never touches `DebtorCredit` and never
 * changes a lot's cost basis.
 *
 * On accept, in one transaction, each item draws from unassigned lots at the
 * branch (`custodian_id IS NULL`) using the SUPPLIER-first priority of business
 * rule 2, and creates a mirror `InventoryEntry` carrying the same `source` and
 * `unit_cost` with `custodian_id` set. A `CUSTODY_OUT`/`CUSTODY_IN` stock
 * movement pair records each leg.
 */
@Entity('stock_issues')
@Index('idx_stock_issues_custody', ['custodyId'])
export class StockIssue {
  @ApiProperty({ example: 'uuid-v4' })
  @PrimaryGeneratedColumn('uuid')
  id: string;

  /** Tenancy: MULTI_SHOP_PLAN.md §3.2. Always the custody's own branch. */
  @Column({ name: 'org_id', type: 'uuid' })
  orgId: string;

  @Column({ name: 'shop_id', type: 'uuid' })
  shopId: string;

  @Column({ name: 'custody_id', type: 'uuid' })
  custodyId: string;

  @ManyToOne(() => StockCustody, { onDelete: 'CASCADE' })
  @JoinColumn({ name: 'custody_id' })
  custody: StockCustody;

  @ApiProperty({ enum: StockIssueStatus, default: StockIssueStatus.PENDING })
  @Column({ type: 'enum', enum: StockIssueStatus, default: StockIssueStatus.PENDING })
  status: StockIssueStatus;

  @ApiPropertyOptional({ description: 'Owner (or delegate) who issued the volume' })
  @Column({ name: 'issued_by_id', type: 'uuid', nullable: true })
  issuedById: string | null;

  @ManyToOne(() => User, { nullable: true, onDelete: 'SET NULL' })
  @JoinColumn({ name: 'issued_by_id' })
  issuedBy: User | null;

  @ApiProperty({
    example: false,
    description:
      'True when this issue was generated by the appointment sweep — every unassigned lot at the branch, pre-filled as lines. Record-only; the accept path is identical.',
  })
  @Column({ name: 'is_opening_sweep', type: 'boolean', default: false })
  isOpeningSweep: boolean;

  @ApiPropertyOptional({ example: 'Opening stock for the week' })
  @Column({ type: 'varchar', nullable: true })
  note: string | null;

  @ApiPropertyOptional({ example: 'Two cartons are damaged, I am not taking them' })
  @Column({ name: 'rejection_reason', type: 'varchar', nullable: true })
  rejectionReason: string | null;

  @OneToMany(() => StockIssueItem, (item) => item.issue, { cascade: true })
  items: StockIssueItem[];

  @CreateDateColumn({ name: 'created_at' })
  createdAt: Date;

  @ApiPropertyOptional()
  @Column({ name: 'accepted_at', type: 'timestamp', nullable: true })
  acceptedAt: Date | null;

  @ApiPropertyOptional()
  @Column({ name: 'rejected_at', type: 'timestamp', nullable: true })
  rejectedAt: Date | null;

  @ApiPropertyOptional()
  @Column({ name: 'cancelled_at', type: 'timestamp', nullable: true })
  cancelledAt: Date | null;

  @UpdateDateColumn({ name: 'updated_at' })
  updatedAt: Date;
}
