const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod, AndroidConfig } = require('expo/config-plugins');

/**
 * `rebuild-local.sh` (without --prod) bakes a plain-HTTP API URL into a *release*
 * APK. Since targetSdk 28 Android blocks cleartext by default, and the template's
 * `android:usesCleartextTraffic="true"` lives only in `app/src/debug/`, which
 * `assembleRelease` never sees. The request then dies inside the app before it
 * hits the network and axios reports a bare "Network Error" — indistinguishable
 * from a backend that is down.
 *
 * So: permit cleartext for local hosts only, and keep it banned everywhere else.
 * `--prod` builds are unaffected (that backend is HTTPS) and stay HTTPS-only.
 *
 * The host of EXPO_PUBLIC_API_URL is added automatically when it is http://, so
 * testing on a real phone over LAN works too — but note this is read at
 * *prebuild* time, not build time, so re-run `pnpm prebuild` after changing the
 * LAN IP in .env.
 */
const RES_NAME = 'network_security_config';

/** Loopback plus the emulator's alias for the host machine. */
const ALWAYS_ALLOWED = ['localhost', '127.0.0.1', '10.0.2.2'];

function cleartextHostFromEnv() {
  const url = process.env.EXPO_PUBLIC_API_URL;
  if (!url) return [];
  try {
    const { protocol, hostname } = new URL(url);
    return protocol === 'http:' ? [hostname] : [];
  } catch {
    return [];
  }
}

function buildXml(domains) {
  const entries = domains
    .map((d) => `    <domain includeSubdomains="false">${d}</domain>`)
    .join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-cleartext-local.js — edits here are lost on prebuild. -->
<network-security-config>
  <base-config cleartextTrafficPermitted="false" />
  <domain-config cleartextTrafficPermitted="true">
${entries}
  </domain-config>
</network-security-config>
`;
}

module.exports = function withCleartextLocal(config) {
  const domains = [...new Set([...ALWAYS_ALLOWED, ...cleartextHostFromEnv()])];

  config = withDangerousMod(config, [
    'android',
    (cfg) => {
      const xmlDir = path.join(
        cfg.modRequest.platformProjectRoot,
        'app/src/main/res/xml',
      );
      fs.mkdirSync(xmlDir, { recursive: true });
      fs.writeFileSync(path.join(xmlDir, `${RES_NAME}.xml`), buildXml(domains));
      return cfg;
    },
  ]);

  return withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    app.$['android:networkSecurityConfig'] = `@xml/${RES_NAME}`;
    return cfg;
  });
};
